export const DICTS: Record<Lang, Dict> = { he, en };

/** Replace each {name} with params[name]; unknown placeholders stay as written. */
export function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

export function translate(dict: Dict, key: Key, params?: Params): string {
  return interpolate(dict[key] ?? en[key] ?? key, params);
}

export function isKey(k: string): k is Key {
  return Object.prototype.hasOwnProperty.call(en, k);
}

/** BCP 47 locale used for numbers, money and dates. */
export function localeFor(lang: Lang): string {
  return lang === 'he' ? 'he-IL' : 'en';
}
